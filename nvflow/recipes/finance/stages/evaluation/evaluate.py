"""Evaluate models on finance benchmarks using nemo-skills.

Evaluation runs in three contexts:

1. **Standalone baseline eval** (``workflow=eval``): evaluates pre-trained
   models listed in ``eval/baselines.yaml``.  Stages are auto-generated by
   ``WorkflowRunner._expand_dynamic_stages()``.

2. **Embedded SFT checkpoint eval** (``workflow=sft``): runs as the last
   stage of an SFT training pipeline.  The ``eval`` stage in each SFT model
   config evaluates training checkpoints at specified steps.

3. **Embedded GRPO checkpoint eval** (``workflow=grpo``): same as above but
   for GRPO RL training checkpoints.  Supports ``format: hf`` (pre-converted)
   and ``format: fsdp`` (DCP→HF conversion on cluster at eval time).

Shared evaluation settings (benchmarks, judges, datasets) are loaded at
runtime from ``eval/base.yaml``.
"""

from pathlib import Path
from typing import Any

from nvflow.core import BaseStage, StageRegistry, console


def _normalize_args(args: str | None) -> str:
    """Normalize multi-line args to single line."""
    return " ".join(args.split()) if args else ""


def _load_eval_base_config() -> dict:
    """Load shared evaluation settings from ``eval/base.yaml``.

    Returns benchmarks, judge, datasets_dir, and conversion config that
    are shared across all evaluation contexts (standalone, SFT, GRPO).
    """
    import yaml

    base_yaml = Path(__file__).parents[2] / "workflows" / "eval" / "base.yaml"
    if not base_yaml.exists():
        return {}
    with open(base_yaml) as f:
        return yaml.safe_load(f) or {}


