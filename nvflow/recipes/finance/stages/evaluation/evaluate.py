def _resolve_model_name(config: dict, base_model_path: str) -> str:
    """Return the HF model path for Megatron-to-HF conversion.

    Uses ``base_model`` (the HF model used for conversion) which may
    differ from ``baseline_model`` (the model evaluated for comparison).
    """
    if not base_model_path:
        raise ValueError(
            "base_model (or baseline_model) path is required for Megatron checkpoint conversion."
        )
    return base_model_path


def _submit_conversion_job(
    megatron_path: Path,
    hf_output_path: Path,
    convert_log_dir: Path,
    model_name: str,
    cluster: str,
    expname: str,
    num_gpus: int = 8,
    installation_command: str | None = None,
    run_after: list[str] | None = None,
) -> str:
    """Submit idempotent Megatron-to-HF conversion job to cluster.

    The job handles detection ON THE CLUSTER where paths are valid:
    - If HF model exists -> skip (no-op)
    - If Megatron exists -> convert
    - If neither -> error
    """
    from nemo_skills.pipeline.cli import run_cmd, wrap_arguments

    from nvflow.recipes.finance.utils.evaluation.checkpoint_converter import (
        build_conversion_script,
    )

    script = build_conversion_script(megatron_path, hf_output_path, model_name)
    command = f"bash -c '{script}'"
    convert_expname = f"{expname}-convert"

    console.status("Submitting checkpoint conversion job (idempotent)")
    console.detail("Megatron path", str(megatron_path))
    console.detail("HF output", str(hf_output_path))
    console.detail("Model", model_name)
    console.detail("GPUs", str(num_gpus))
    console.detail("Logs", str(convert_log_dir))
    if installation_command:
        console.detail(
            "Installation cmd",
            installation_command[:50] + "..."
            if len(installation_command) > 50
            else installation_command,
        )

    run_cmd(
        ctx=wrap_arguments(command),
        cluster=cluster,
        container="nemo-rl",
        num_gpus=num_gpus,
        log_dir=str(convert_log_dir),
        expname=convert_expname,
        installation_command=installation_command,
        run_after=run_after,
    )

    console.success(f"Conversion job submitted: {convert_expname}")
    return convert_expname


def _submit_dcp_conversion_job(
    checkpoint_path: str,
    step: int,
    hf_output_path: Path,
    convert_log_dir: Path,
    cluster: str,
    expname: str,
    num_gpus: int = 1,
    installation_command: str | None = None,
    run_after: list[str] | None = None,
) -> str:
    """Submit idempotent DCP (FSDP) → HF conversion job to cluster.

    Same pattern as ``_submit_conversion_job``: pure string math at submit
    time; the bash script resolves the run subdirectory on the cluster.
    """
    from nemo_skills.pipeline.cli import run_cmd, wrap_arguments

    from nvflow.recipes.finance.utils.evaluation.checkpoint_converter import (
        build_dcp_conversion_script,
    )

    script = build_dcp_conversion_script(checkpoint_path, step, hf_output_path)
    command = f"bash -c '{script}'"
    convert_expname = f"{expname}-convert"

    console.status("Submitting DCP→HF checkpoint conversion job (idempotent)")
    console.detail("Checkpoint path", str(checkpoint_path))
    console.detail("Step", str(step))
    console.detail("HF output", str(hf_output_path))
    console.detail("GPUs", str(num_gpus))

    run_cmd(
        ctx=wrap_arguments(command),
        cluster=cluster,
        container="nemo-rl",
        num_gpus=num_gpus,
        log_dir=str(convert_log_dir),
        expname=convert_expname,
        installation_command=installation_command,
        run_after=run_after,
    )

    console.success(f"DCP conversion job submitted: {convert_expname}")
    return convert_expname


