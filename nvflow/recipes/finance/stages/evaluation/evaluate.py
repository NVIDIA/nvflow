def _get_eval_stages_from_yaml() -> tuple[list[str], list[str]]:
    """Discover eval stage names from ``eval/baselines.yaml``.

    Scans for ``models`` and ``checkpoints`` sections and returns the
    stage names that need to be registered under ``workflow=eval``.
    """
    import yaml

    static_stages: list[str] = []
    checkpoint_stages: list[str] = []

    workflows_dir = Path(__file__).parents[2] / "workflows"
    eval_dir = workflows_dir / "eval"
    if not eval_dir.exists():
        return static_stages, checkpoint_stages

    for yaml_file in sorted(eval_dir.glob("*.yaml")):
        if yaml_file.stem == "base":
            continue

        try:
            with open(yaml_file) as f:
                config = yaml.safe_load(f)

            if not config:
                continue

            if "models" in config:
                for model_name in config["models"]:
                    if model_name not in static_stages:
                        static_stages.append(model_name)

            runs = config.get("checkpoints", config.get("training_runs", {}))
            if runs:
                for run_name, run_config in runs.items():
                    for step in run_config.get("eval_steps", []):
                        stage_name = f"{run_name}-{step}"
                        if stage_name not in checkpoint_stages:
                            checkpoint_stages.append(stage_name)

        except Exception as e:
            import warnings

            warnings.warn(f"Failed to parse {yaml_file}: {e}", stacklevel=2)

    return static_stages, checkpoint_stages


_static_stages, _checkpoint_stages = _get_eval_stages_from_yaml()

for _stage_name in _static_stages:
    StageRegistry.register(recipe="finance", workflow="eval", stage=_stage_name)(
        _BaseFinanceEvaluator
    )

for _stage_name in _checkpoint_stages:
    StageRegistry.register(recipe="finance", workflow="eval", stage=_stage_name)(
        _CheckpointEvaluator
    )
