def _format_benchmarks(benchmarks_config: dict | list) -> list[str]:
    """Convert benchmarks config to ``["name:seeds", ...]`` format.

    Accepts either a dict (``{secque: {seeds: 5}, ...}``) or a
    pre-formatted list (``["secque:5", ...]``).  Entries set to
    ``None`` (disabled benchmarks) are filtered out.
    """
    if isinstance(benchmarks_config, dict):
        return [
            f"{name}:{cfg.get('seeds', 1)}"
            for name, cfg in benchmarks_config.items()
            if cfg is not None
        ]
    if isinstance(benchmarks_config, list):
        return benchmarks_config
    return []


class _BaseFinanceEvaluator(BaseStage):
    """Evaluate a model on finance benchmarks using nemo-skills.

    Handles both baseline models (skip_conversion=true) and Megatron
    checkpoints (skip_conversion=false, auto-converts on cluster).

    When invoked as an auto-expanded model stage (``_source_section ==
    "models"``), the raw model config is transformed into the standard
    eval config format using shared settings from ``eval/base.yaml``.
    """

    def _build_config_from_model(self, raw_config: dict[str, Any]) -> dict[str, Any]:
        """Transform a raw model entry into the standard eval config.

        Called when the stage was auto-generated from the ``models``
        section by ``WorkflowRunner._expand_dynamic_stages()``.

        Workflow-level keys (``benchmarks``, ``judge``, ``datasets_dir``,
        ``base_output_dir``) are already present in ``raw_config`` as
        defaults forwarded by the runner.  Falls back to ``eval/base.yaml``
        for any missing shared settings.
        """
        base = _load_eval_base_config()
        model_name = raw_config.get("_source_name", "unknown")
        base_output_dir = raw_config.get(
            "base_output_dir",
            base.get("base_output_dir", "./outputs"),
        )

        benchmarks = raw_config.get("benchmarks", base.get("benchmarks", {}))
        judge = raw_config.get("judge", base.get("judge"))
        datasets_dir = raw_config.get("datasets_dir", base.get("datasets_dir"))

        return {
            "benchmarks": _format_benchmarks(benchmarks),
            "datasets_dir": datasets_dir,
            "judge": judge,
            "output_dir": f"{base_output_dir}/{model_name}",
            "rollouts": {
                "model": raw_config["path"],
                "skip_conversion": True,
                "server_type": raw_config.get("server_type", "vllm"),
                "server_gpus": raw_config.get("gpus", 1),
                "server_nodes": raw_config.get("nodes", 1),
                "extra_args": raw_config.get("inference_args", ""),
            },
            "stage_kwargs": {
                "server_args": raw_config.get("server_args", ""),
            },
        }

    def _prepare_model_for_eval(
        self,
        config: dict[str, Any],
        rollouts: dict[str, Any],
        cluster: str,
        expname: str,
        run_after: list[str] | None = None,
    ) -> tuple[str, str | None]:
        """Return (effective_model_path, conversion_job_name | None)."""
        skip_conversion = rollouts.get("skip_conversion", True)

        if skip_conversion:
            model_path = rollouts.get("model") or rollouts.get("path")
            console.detail("Conversion", "skipped (skip_conversion=true)")
            return str(model_path), None

        from nvflow.recipes.finance.utils.evaluation.checkpoint_converter import (
            get_hf_output_paths,
        )

        run_path_str = config.get("_run_path")
        step = config.get("_step")
        if not run_path_str or not step:
            raise ValueError(
                "_run_path and _step are required for checkpoint conversion. "
                "Either provide them or set skip_conversion=true."
            )

        run_path = Path(run_path_str)
        conversion_config = config.get("conversion", {})

        if config.get("_conversion_type") == "dcp":
            hf_model_path, convert_log_dir = get_hf_output_paths(run_path, step)
            conversion_job = _submit_dcp_conversion_job(
                checkpoint_path=run_path_str,
                step=step,
                hf_output_path=hf_model_path,
                convert_log_dir=convert_log_dir,
                cluster=cluster,
                expname=expname,
                num_gpus=conversion_config.get("num_gpus", 1),
                installation_command=conversion_config.get("installation_command"),
                run_after=run_after,
            )
            return str(hf_model_path), conversion_job

        megatron_path = run_path / "checkpoints" / f"step_{step}"
        hf_model_path, convert_log_dir = get_hf_output_paths(run_path, step)
        model_name = _resolve_model_name(config, rollouts.get("base_model", ""))

        conversion_job = _submit_conversion_job(
            megatron_path=megatron_path,
            hf_output_path=hf_model_path,
            convert_log_dir=convert_log_dir,
            model_name=model_name,
            cluster=cluster,
            expname=expname,
            num_gpus=conversion_config.get("num_gpus", 8),
            installation_command=conversion_config.get("installation_command"),
            run_after=run_after,
        )

        return str(hf_model_path), conversion_job

    def execute(
        self,
        config: dict[str, Any],
        cluster: str,
        expname: str,
        run_after: list[str] | None = None,
    ) -> None:
        from nemo_skills.pipeline.cli import eval as nemo_eval
        from nemo_skills.pipeline.cli import wrap_arguments

        if config.get("_source_section") == "models":
            config = self._build_config_from_model(config)

        rollouts = config.get("rollouts", {})
        judge = config.get("judge", {})
        stage_kwargs = config.get("stage_kwargs", {})

        # Step 1: Handle checkpoint conversion (if needed)
        # Build dependency list early so conversion jobs also wait for upstream
        eval_run_after = list(run_after) if run_after else []

        effective_model_path, conversion_job = self._prepare_model_for_eval(
            config=config,
            rollouts=rollouts,
            cluster=cluster,
            expname=expname,
            run_after=eval_run_after or None,
        )

        if conversion_job:
            eval_run_after.append(conversion_job)
            console.info(f"Eval will run after conversion job: {conversion_job}")

        # Step 2: Extract evaluation configuration
        server_type = rollouts.get("server_type", "vllm")
        server_address = rollouts.get("server_address")
        server_gpus = rollouts.get("server_gpus")
        server_nodes = rollouts.get("server_nodes", 1)
        extra_args = _normalize_args(rollouts.get("extra_args"))

        if enabled_tools := rollouts.get("enabled_tools"):
            tools_str = (
                "__".join(enabled_tools)
                if isinstance(enabled_tools, list)
                else str(enabled_tools).replace(",", "__").replace(";", "__")
            )
            extra_args = f"{extra_args} ++enabled_tools={tools_str}".strip()

        judge_model = judge.get("model")
        judge_server_type = judge.get("server_type")
        judge_server_address = judge.get("server_address")
        judge_server_gpus = judge.get("server_gpus")
        judge_server_nodes = judge.get("server_nodes")
        extra_judge_args = _normalize_args(judge.get("extra_args"))

        output_dir = config.get("output_dir", "./outputs/finance_eval")
        benchmarks = config.get("benchmarks", ["secque:1"])
        if isinstance(benchmarks, list):
            benchmarks = ",".join(benchmarks)

        installation_command = config.get("installation_command")
        num_jobs = config.get("num_jobs")
        single_node_mode = config.get("single_node_mode")

        datasets_dir = config.get("datasets_dir")
        if not datasets_dir or not Path(datasets_dir).is_absolute():
            raise ValueError(
                f"datasets_dir must be an absolute path, got: '{datasets_dir}'. "
                "Example: datasets_dir: /workspace/nvflow/recipes/finance/datasets"
            )

        # Step 3: Skip-if-done check
        # If all benchmark metrics already exist, skip this stage entirely.
        benchmark_names = [b.split(":")[0] for b in benchmarks.split(",")]
        remaining = []
        for bname in benchmark_names:
            metrics_path = Path(output_dir) / "eval-results" / bname / "metrics.json"
            if metrics_path.exists():
                console.info(f"Skipping {bname} — metrics.json already exists at {metrics_path}")
            else:
                remaining.append(bname)

        if not remaining:
            console.success("All benchmarks already completed — nothing to submit")
            return

        if len(remaining) < len(benchmark_names):
            skipped = set(benchmark_names) - set(remaining)
            console.info(f"Skipped {len(skipped)} completed benchmark(s): {', '.join(skipped)}")
            benchmarks_to_run = ",".join(
                b for b in benchmarks.split(",") if b.split(":")[0] in remaining
            )
        else:
            benchmarks_to_run = benchmarks

        # Step 4: Submit eval job
        console.status("Evaluating on finance benchmarks")
        console.detail("Model", effective_model_path or server_address)
        console.detail("Benchmarks", benchmarks_to_run)
        console.detail("Output", output_dir)
        console.detail("Judge", judge_model or judge_server_address)
        if eval_run_after:
            console.detail("Dependencies", ", ".join(eval_run_after))
        console.blank()

        try:
            eval_kwargs = {
                "ctx": wrap_arguments(extra_args),
                "cluster": cluster,
                "output_dir": output_dir,
                "log_dir": f"{output_dir}/logs",
                "benchmarks": benchmarks_to_run,
                "expname": expname,
                "data_dir": datasets_dir,
                "extra_datasets": "nvflow/recipes/finance/datasets",
                "extra_datasets_type": "local",
                "model": effective_model_path,
                "server_address": server_address,
                "server_type": server_type,
                "server_gpus": server_gpus,
                "server_nodes": server_nodes,
                "run_after": eval_run_after or None,
                "judge_model": judge_model,
                "judge_server_address": judge_server_address,
                "judge_server_type": judge_server_type,
                "judge_server_gpus": judge_server_gpus,
                "judge_server_nodes": judge_server_nodes,
                "judge_generation_module": "nvflow.recipes.finance.datasets.finance_judge",
                "extra_judge_args": extra_judge_args,
                **stage_kwargs,
            }

            if num_jobs is not None:
                eval_kwargs["num_jobs"] = num_jobs
            if single_node_mode is not None:
                eval_kwargs["single_node_mode"] = single_node_mode
            if installation_command:
                eval_kwargs["installation_command"] = installation_command

            result = nemo_eval(**eval_kwargs)

            console.success("Evaluation job submitted")
            console.detail("Results will be at", output_dir)
            return result

        except Exception as e:
            console.error(f"Evaluation failed: {e}")
            raise


class EmbeddedEvalStage(_BaseFinanceEvaluator):
    """Eval stage embedded in SFT or GRPO training pipelines.

    Reads shared settings (benchmarks, judge, datasets_dir, conversion) from
    ``eval/base.yaml`` at runtime, then merges with the per-model eval config
    from the training YAML.  Iterates over ``eval_steps`` and evaluates each
    checkpoint, supporting both Megatron and HF formats.

    Automatically prepares benchmark datasets (via ``PrepareFinanceBenchmarksStage``)
    as the first sub-step so that the eval stage is self-contained and does not
    require a separate ``prepare_data`` pipeline stage.
    """

    def _prepare_benchmark_data(
        self,
        base_config: dict[str, Any],
        cluster: str,
        expname: str,
        run_after: list[str] | None = None,
    ) -> str:
        """Submit benchmark dataset preparation job and return its expname.

        Reads the ``stages.prepare_data`` config from ``eval/base.yaml`` and
        delegates to ``PrepareFinanceBenchmarksStage``.  The job is idempotent —
        re-running when data already exists is a fast no-op on the cluster.
        """
        from nvflow.recipes.finance.stages.evaluation.prepare_data import (
            PrepareFinanceBenchmarksStage,
        )

        prep_config = base_config.get("stages", {}).get("prepare_data", {})
        if not prep_config:
            console.info("No prepare_data config in eval/base.yaml — skipping data prep")
            return ""

        prep_expname = f"{expname}-prepare-data"
        console.info("Preparing benchmark datasets before evaluation")

        stage = PrepareFinanceBenchmarksStage()
        stage.execute(
            config=prep_config,
            cluster=cluster,
            expname=prep_expname,
            run_after=run_after,
        )

        return prep_expname

    def execute(
        self,
        config: dict[str, Any],
        cluster: str,
        expname: str,
        run_after: list[str] | None = None,
    ) -> None:
        base_config = _load_eval_base_config()

        eval_steps = config.get("eval_steps", [])
        if isinstance(eval_steps, int):
            eval_steps = [eval_steps]
        if not eval_steps:
            console.info("No eval_steps configured — skipping evaluation")
            return

        # Sub-step 0: prepare benchmark datasets (idempotent)
        prep_expname = self._prepare_benchmark_data(
            base_config=base_config,
            cluster=cluster,
            expname=expname,
            run_after=run_after,
        )

        # All eval jobs depend on prepare_data completing first
        eval_run_after = list(run_after) if run_after else []
        if prep_expname:
            eval_run_after.append(prep_expname)

        checkpoint_format = config.get("format", "megatron")
        checkpoint_path = config.get("checkpoint_path", "")
        baseline_model = config.get("baseline_model", "")
        base_model = config.get("base_model", "") or baseline_model
        base_output_dir = config.get("base_output_dir", "")
        eval_output_dir = config.get("eval_output_dir", f"{base_output_dir}/step-5-eval")

        benchmarks_list = _format_benchmarks(
            config.get("benchmarks", base_config.get("benchmarks", {}))
        )

        for step in eval_steps:
            console.info(f"Evaluating checkpoint step {step} (format: {checkpoint_format})")

            if checkpoint_format == "hf":
                model_path = str(Path(checkpoint_path) / f"step_{step}" / "policy")
                stage_config = {
                    "benchmarks": benchmarks_list,
                    "datasets_dir": base_config.get("datasets_dir"),
                    "judge": base_config.get("judge"),
                    "output_dir": f"{eval_output_dir}/step-{step}",
                    "rollouts": {
                        "model": model_path,
                        "skip_conversion": True,
                        "server_type": config.get("server_type", "vllm"),
                        "server_gpus": config.get("gpus", 1),
                        "server_nodes": config.get("nodes", 1),
                        "extra_args": config.get("inference_args", ""),
                    },
                    "stage_kwargs": {
                        "server_args": config.get("server_args", ""),
                    },
                }
            elif checkpoint_format == "fsdp":
                stage_config = {
                    "_run_path": str(checkpoint_path),
                    "_step": step,
                    "_conversion_type": "dcp",
                    "benchmarks": benchmarks_list,
                    "datasets_dir": base_config.get("datasets_dir"),
                    "judge": base_config.get("judge"),
                    "conversion": base_config.get("conversion", {}),
                    "output_dir": f"{eval_output_dir}/step-{step}",
                    "rollouts": {
                        "skip_conversion": False,
                        "server_type": config.get("server_type", "vllm"),
                        "server_gpus": config.get("gpus", 1),
                        "server_nodes": config.get("nodes", 1),
                        "extra_args": config.get("inference_args", ""),
                    },
                    "stage_kwargs": {
                        "server_args": config.get("server_args", ""),
                    },
                }
            else:
                run_path = Path(checkpoint_path)
                from nvflow.recipes.finance.utils.evaluation.checkpoint_converter import (
                    get_hf_output_paths,
                )

                hf_model_path, _ = get_hf_output_paths(run_path, step)
                conversion_config = base_config.get("conversion", {})
                stage_config = {
                    "_run_path": str(run_path),
                    "_step": step,
                    "benchmarks": benchmarks_list,
                    "datasets_dir": base_config.get("datasets_dir"),
                    "judge": base_config.get("judge"),
                    "conversion": conversion_config,
                    "output_dir": f"{eval_output_dir}/step-{step}",
                    "rollouts": {
                        "base_model": base_model,
                        "skip_conversion": False,
                        "server_type": config.get("server_type", "vllm"),
                        "server_gpus": config.get("gpus", 1),
                        "server_nodes": config.get("nodes", 1),
                        "extra_args": config.get("inference_args", ""),
                    },
                    "stage_kwargs": {
                        "server_args": config.get("server_args", ""),
                    },
                }

            super().execute(
                config=stage_config,
                cluster=cluster,
                expname=f"{expname}-step{step}",
                run_after=eval_run_after,
            )

        # Also evaluate baseline model if configured
        if baseline_model:
            console.info(f"Evaluating baseline model: {baseline_model}")
            baseline_config = {
                "benchmarks": benchmarks_list,
                "datasets_dir": base_config.get("datasets_dir"),
                "judge": base_config.get("judge"),
                "output_dir": f"{eval_output_dir}/baseline",
                "rollouts": {
                    "model": baseline_model,
                    "skip_conversion": True,
                    "server_type": config.get("server_type", "vllm"),
                    "server_gpus": config.get("gpus", 1),
                    "server_nodes": config.get("nodes", 1),
                    "extra_args": config.get("inference_args", ""),
                },
                "stage_kwargs": {
                    "server_args": config.get("server_args", ""),
                },
            }
            super().execute(
                config=baseline_config,
                cluster=cluster,
                expname=f"{expname}-baseline",
                run_after=eval_run_after,
            )


class _CheckpointEvaluator(_BaseFinanceEvaluator):
    """Evaluator for auto-generated checkpoint stages in standalone eval workflows.

    Receives raw checkpoint config from ``WorkflowRunner._expand_dynamic_stages()``
    with ``_source_section == "checkpoints"`` and ``_step`` metadata.  Builds the
    standard eval config and delegates to ``_BaseFinanceEvaluator.execute()``.
    """

    def execute(
        self,
        config: dict[str, Any],
        cluster: str,
        expname: str,
        run_after: list[str] | None = None,
    ) -> None:
        run_name = config.get("_source_name")
        step = config.get("_step")
        base_output_dir = config.get("base_output_dir", "./outputs")

        if not run_name or not step:
            raise ValueError(
                f"Checkpoint stage missing _source_name or _step. "
                f"Got: run_name={run_name}, step={step}"
            )

        run_path = Path(config.get("path", ""))
        checkpoint_format = config.get("format", "megatron")

        console.info(f"Checkpoint: {run_name}, step: {step}, format: {checkpoint_format}")
        console.detail("Run path", str(run_path))

        base = _load_eval_base_config()
        benchmarks = config.get("benchmarks", base.get("benchmarks", {}))
        common = {
            "benchmarks": _format_benchmarks(benchmarks),
            "datasets_dir": config.get("datasets_dir", base.get("datasets_dir")),
            "judge": config.get("judge", base.get("judge")),
        }

        if checkpoint_format == "hf":
            hf_model_path = str(run_path / f"step_{step}" / "policy")
            stage_config = {
                **common,
                "output_dir": f"{base_output_dir}/{run_name}-{step}",
                "rollouts": {
                    "model": hf_model_path,
                    "skip_conversion": True,
                    "server_type": config.get("server_type", "vllm"),
                    "server_gpus": config.get("gpus", 1),
                    "server_nodes": config.get("nodes", 1),
                    "extra_args": config.get("inference_args", ""),
                },
                "stage_kwargs": {
                    "server_args": config.get("server_args", ""),
                },
            }
        else:
            stage_config = {
                **common,
                "_run_path": str(run_path),
                "_step": step,
                "output_dir": f"{base_output_dir}/{run_name}-{step}",
                "conversion": base.get("conversion", {}),
                "rollouts": {
                    "base_model": config.get("base_model"),
                    "skip_conversion": False,
                    "server_type": config.get("server_type", "vllm"),
                    "server_gpus": config.get("gpus", 1),
                    "server_nodes": config.get("nodes", 1),
                    "extra_args": config.get("inference_args", ""),
                },
                "stage_kwargs": {
                    "server_args": config.get("server_args", ""),
                },
            }

        return super().execute(
            config=stage_config,
            cluster=cluster,
            expname=expname,
            run_after=run_after,
        )


